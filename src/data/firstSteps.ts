export function makeGuidePractice(section:GuideSection,locale:'ru'|'uk',random= Math.random){
    const shuffledCopy=<T,>(values:T[])=>{const result=[...values];for(let i=result.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[result[i],result[j]]=[result[j],result[i]];}return result;};
    const eligible=section.rows.filter(row=>!row.german.includes('…'));
    const shuffled=shuffledCopy(eligible).slice(0,10);
    return shuffled.map(row=>{const correct=row.translation[locale];const alternatives=shuffledCopy([...new Set(section.rows.filter(other=>other.id!==row.id).map(other=>other.translation[locale]))].filter(value=>value!==correct)).slice(0,3);return {row,options:shuffledCopy([correct,...alternatives])};});
}

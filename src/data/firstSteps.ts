export function guideTag(row:GuideRow,sectionId:string,locale:'ru'|'uk'){
    if(sectionId!=='alphabet'||locale==='uk')return row.tag;
    const letter=row.tag?.split(' · ')[0]??'';
    return russianLetterNames[letter]?`${letter} · ${russianLetterNames[letter]}`:row.tag;
}
